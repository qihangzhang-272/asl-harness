const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const {WorkspaceDomain}=require('../domain.cjs');
test('native plugin reuses the real CLI write, fingerprint and Mermaid render gate',async t=>{
  const sourceRoot=path.resolve(__dirname,'../../..'),storage=await fs.mkdtemp(path.join(os.tmpdir(),'asl-dsh-core-'));
  t.after(async()=>{assert.ok(path.resolve(storage).startsWith(path.resolve(os.tmpdir())+path.sep));await fs.rm(storage,{recursive:true,force:true});});
  const environment=path.join(storage,'environment');
  await fs.cp(path.join(sourceRoot,'examples/personal-environment'),environment,{recursive:true});
  const d=new WorkspaceDomain({sourceRoot,environment,storage,python:process.env.ASL_PYTHON});
  const extra=path.join(environment,'skills','visual-draft');
  await fs.mkdir(extra,{recursive:true});
  await fs.writeFile(path.join(extra,'SKILL.md'),'---\nname: visual-draft\ndescription: 将材料整理为视觉草稿。\n---\n\n# 视觉草稿\n\n整理输入材料。\n');
  await fs.writeFile(path.join(extra,'SOURCE.md'),'# Source\n\n- Origin: 本地集成测试样例\n');
  const catalog=await d.catalog(),mode=catalog.modes[0];
  const original=await d.read('mode',mode.id,'MODE.md');
  const draft=({kind:'mode',identifier:mode.id,document:original.document+'\n\n## DSH 核验\n\n```mermaid\nflowchart LR\n a[研究] --> b[表达]\n%% asl-bind b ["visual-draft"]\n```\n',expected:original.fingerprint,skills:['visual-draft']});
  assert.equal((await d.read('mode',mode.id,'MODE.md')).document,original.document);
  const context=d.updateContext('native-fixture',{mode:mode.id,kind:'mode',identifier:mode.id,file:'MODE.md'});
  await d.dispatch('save',{...draft,contextRevision:context.contextRevision},{sessionId:'native-fixture'});
  const saved=await d.read('mode',mode.id,'MODE.md');assert.ok(saved.document.includes('DSH 核验'));
  const updated=(await d.catalog()).modes.find(m=>m.id===mode.id);
  assert.ok(updated.skills.includes('visual-draft'));
  assert.ok(updated.architecture.shared.includes('visual-draft'));
  assert.deepEqual(updated.architecture.paradigms,mode.architecture.paradigms);
  const invalid=({kind:'mode',identifier:mode.id,document:saved.document+'\n```mermaid\nflowchart LR\n a[broken\n```\n',expected:saved.fingerprint});
  await assert.rejects(()=>d.save(invalid),error=>error.code==='MERMAID_RENDER_FAILED');
  assert.equal((await d.read('mode',mode.id,'MODE.md')).fingerprint,saved.fingerprint);
  const old=({kind:'mode',identifier:mode.id,document:saved.document+'\n旧草稿\n',expected:saved.fingerprint});
  await fs.appendFile(path.join(environment,'modes',mode.id,'MODE.md'),'\n外部编辑\n');
  await assert.rejects(()=>d.save(old),/原文件已变化/);
});
